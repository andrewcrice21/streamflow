import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)

v = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        v[i] = RA - (q1 * x[i])
    elif 2 <= x[i] < 4:
        v[i] = RA - (q1 * 2) - P1
    else:
        v[i] = RA - (q1 * 2) - P1 + RB - (q2 * (x[i] - 4))

plt.figure()
plt.plot(x, v)
plt.fill_between(x, v, color='skyblue', alpha=0.4)
plt.axhline(0, color='black', linewidth=0.8)
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.title('Shear Diagram')
plt.grid(True)
plt.show()

# This code first defines the variables as well as x and v
# It then runs a for loop defining the piecewise shear function
# It then plots the results on diagram and prints the output

